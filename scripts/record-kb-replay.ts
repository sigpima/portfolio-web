/*
 * Records real Knowledge Base runs for the replay shown to visitors without an invite.
 *
 *   npm run record:kb                       # chat service at http://127.0.0.1:8003
 *   npm run record:kb -- --url http://host:8003
 *
 * Talks DIRECTLY to the `chat` service (not through portfolio-api, no invite needed):
 * asks each question of `scripts/kb-replay-questions.json` in a fresh conversation,
 * timestamps every SSE event with the real clock, turns the run into a replay sample
 * (`buildReplaySample`) and overwrites `src/content/replays/knowledge-base.recorded.ts`.
 * Samples written here are never placeholders. Nothing is written unless every
 * question got a real answer: an unreachable/disabled service or an error stops it.
 */
import { writeFile as fsWriteFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import type { ReplaySample } from "../src/content/replays/types";
import { parseSse } from "../src/lib/chat/sse";
import { buildReplaySample, type TimedChatEvent } from "../src/lib/replay/from-chat-events";
import questions from "./kb-replay-questions.json";

const DEFAULT_URL = "http://127.0.0.1:8003";
const STREAM_TIMEOUT_MS = 120_000;
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const OUTPUT_PATH = path.join(ROOT, "src/content/replays/knowledge-base.recorded.ts");

export interface Deps {
  fetch: (url: string, init?: RequestInit) => Promise<Response>;
  /** Milliseconds from a monotonic clock. */
  now: () => number;
  writeFile: (file: string, text: string) => Promise<void>;
  log: (message: string) => void;
  error: (message: string) => void;
}

class RecordError extends Error {}

export function parseArgs(argv: string[]): { url: string } {
  let url = DEFAULT_URL;
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--url" && argv[i + 1]) url = argv[++i];
    else if (arg.startsWith("--url=")) url = arg.slice("--url=".length);
  }
  return { url: url.replace(/\/+$/, "") };
}

export function renderRecordedFile(samples: ReplaySample[]): string {
  const body = samples.length === 0 ? "[]" : JSON.stringify(samples, null, 2);
  return [
    "// Generated by `npm run record:kb` (scripts/record-kb-replay.ts) from real runs of the chat service. Do not edit by hand.",
    'import type { ReplaySample } from "./types";',
    "",
    `export const recordedSamples: ReplaySample[] = ${body};`,
    "",
  ].join("\n");
}

async function checkStatus(url: string, deps: Deps): Promise<void> {
  let res: Response;
  try {
    res = await deps.fetch(`${url}/chat/status`);
  } catch (err) {
    throw new RecordError(
      `Không với tới dịch vụ chat ở ${url} (unreachable): ${err instanceof Error ? err.message : String(err)}. ` +
        "Hãy chạy `docker compose --profile chat up` trong knowledge_base hoặc truyền --url.",
    );
  }
  const body: unknown = res.ok ? await res.json().catch(() => null) : null;
  const enabled = !!body && typeof body === "object" && "enabled" in body && body.enabled === true;
  if (!res.ok) throw new RecordError(`GET ${url}/chat/status trả về ${res.status}.`);
  if (!enabled) throw new RecordError(`Dịch vụ chat ở ${url} đang tắt (disabled: CHAT_DEMO_ENABLED=false).`);
}

async function recordOne(
  url: string,
  q: (typeof questions)[number],
  deps: Deps,
): Promise<ReplaySample> {
  const startedAt = deps.now();
  let res: Response;
  try {
    res = await deps.fetch(`${url}/chat/stream`, {
      method: "POST",
      headers: { "content-type": "application/json", accept: "text/event-stream" },
      // A fresh conversation per question.
      body: JSON.stringify({ message: q.question, session_id: null }),
      signal: AbortSignal.timeout(STREAM_TIMEOUT_MS),
    });
  } catch (err) {
    throw new RecordError(`${q.id}: không với tới ${url}/chat/stream (unreachable): ${String(err)}`);
  }
  if (!res.ok || !res.body) {
    const text = await res.text().catch(() => "");
    throw new RecordError(`${q.id}: POST ${url}/chat/stream trả về ${res.status} ${text.slice(0, 200)}`);
  }
  const events: TimedChatEvent[] = [];
  for await (const event of parseSse(res.body)) {
    events.push({ atMs: deps.now() - startedAt, event });
    if (event.type === "error") {
      throw new RecordError(`${q.id}: chat báo lỗi ${event.code}: ${event.message}`);
    }
  }
  if (!events.some((e) => e.event.type === "answer")) {
    throw new RecordError(`${q.id}: luồng kết thúc mà không có câu trả lời.`);
  }
  return buildReplaySample(events, {
    id: q.id,
    title: q.title,
    // The bot answers in the question's language, so the question is shown as asked.
    question: { vi: q.question, en: q.question },
  });
}

export async function main(argv: string[], deps: Deps): Promise<number> {
  const { url } = parseArgs(argv);
  try {
    await checkStatus(url, deps);
    const samples: ReplaySample[] = [];
    for (const q of questions) {
      deps.log(`Đang ghi ${q.id}…`);
      samples.push(await recordOne(url, q, deps));
    }
    await deps.writeFile(OUTPUT_PATH, renderRecordedFile(samples));
    deps.log(`Đã ghi ${samples.length} mẫu vào ${path.relative(ROOT, OUTPUT_PATH)}.`);
    return 0;
  } catch (err) {
    deps.error(err instanceof RecordError ? err.message : `Lỗi không mong đợi: ${String(err)}`);
    deps.error("Không ghi tệp nào.");
    return 1;
  }
}

